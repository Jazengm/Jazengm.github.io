// These short fragments are only safe when they occupy a whole text node.
const exactOnly = new Set([
  "of",
  "For",
  "and",
  "View",
  "Type",
  "Tag",
  "Note",
  "Current",
  "Past",
]);
const phrases = Object.keys(chinese)
  .filter((key) => !exactOnly.has(key))
  .sort((a, b) => b.length - a.length);
const escaped = phrases.map((text) => {
  const escapedText = text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const start = /^[\p{L}\p{N}_]/u.test(text) ? "(?<![\\p{L}\\p{N}_])" : "";
  const end = /[\p{L}\p{N}_]$/u.test(text) ? "(?![\\p{L}\\p{N}_])" : "";
  return start + escapedText + end;
});
const pattern = new RegExp(escaped.join("|"), "gu");

export type Locale = "en" | "zh-CN";
export function translate(text: string, locale: Locale): string {
  if (locale === "en") return text;
  const normalized = text.replace(/\s+/g, " ").trim();
  const powers = normalized.match(/^First (\d+) powers of one half$/);
  if (powers) return `二分之一的前 ${powers[1]} 个幂`;
  if (normalized.startsWith("View "))
    return `查看 ${translate(normalized.slice(5), locale)}`;
  const exact = chinese[normalized];
  if (exact) return text.replace(/\S[\s\S]*\S|\S/, exact);
  return text.replace(pattern, (phrase) => chinese[phrase]);
}
